"""`gates tests brief <change>` (split-test-author task 4.1, design D9): the
test author's inputs, generated by the shim from the change, the manifest
and the rules-doc, never written by an agent.

Stdlib only, per `zero-dep-shim`. Run with: python3 -m unittest discover -s tests
"""

import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
GATES_SHIM = REPO / "bin" / "gates"
CHANGE = "demo-change"

RICH_MANIFEST = """\
gatesVersion: 1
gates:
  ci: "true"
  unit: "touch unit-ran"
surfaces:
  - name: core
    match: "src/**"
    rules:
      - small-functions
conventions:
  rules-doc: docs/conventions.md
"""

RULES_DOC = """\
# Conventions

### tests-live-beside-code
Applies to: tests
Rule: Put each module's tests in `tests/`, named `test_<module>.py`.

Build on `tests/helpers.py` for shared setup.

### small-functions
Applies to: code
Rule: Keep functions small.
"""

TASKS = """\
## 1. Calc

- [ ] 1.1 Add `add` to `src/calc.py`
- [ ] 1.2 Document it in `README.md`
"""


def _git(cwd, *args):
    subprocess.run(["git", *args], cwd=cwd, check=True, capture_output=True, text=True)


def _write(root, rel, text):
    p = root / rel
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(text)


def _project(tmp, manifest, files):
    root = Path(tmp)
    _git(root, "init", "-b", "main")
    _git(root, "config", "user.email", "t@example.com")
    _git(root, "config", "user.name", "T")
    _write(root, ".gates.yaml", manifest)
    change = f"openspec/changes/{CHANGE}"
    _write(root, f"{change}/tasks.md", TASKS)
    _write(root, f"{change}/design.md", "# Design\n")
    _write(root, f"{change}/specs/calc/spec.md", "## ADDED Requirements\n")
    _write(root, "src/calc.py", "def add(a, b): ...\n")
    for rel, text in files.items():
        _write(root, rel, text)
    _git(root, "add", "-A")
    _git(root, "commit", "-m", "init")
    return root


def _brief(root):
    result = subprocess.run(
        [sys.executable, str(GATES_SHIM), "tests", "brief", CHANGE],
        cwd=root, capture_output=True, text=True,
    )
    assert result.returncode == 0, result.stderr
    sections, current = {}, None
    for line in result.stdout.splitlines():
        if line.startswith("## "):
            current = line[3:].strip()
            sections[current] = []
        elif current is not None:
            sections[current].append(line)
    return {k: "\n".join(v) for k, v in sections.items()}


class TestBriefNamesTheProjectsConventions(unittest.TestCase):
    """Regressions guarded: the author guessing the project's conventions —
    a test rule, a surface rule, the runner, the test layout or the shared
    fixtures missing from its brief — or the brief running the unit gate."""

    def test_every_section(self):
        with tempfile.TemporaryDirectory() as tmp:
            root = _project(tmp, RICH_MANIFEST, {
                "docs/conventions.md": RULES_DOC,
                "tests/test_calc.py": "",
                "tests/helpers.py": "",
                "tests/fixtures/sample.json": "{}",
                "docs/guide.md": "",
            })
            s = _brief(root)
            ran = (root / "unit-ran").exists()

        change = f"openspec/changes/{CHANGE}"
        self.assertIn(f"{change}/tasks.md", s["Artifacts"])
        self.assertIn(f"{change}/design.md", s["Artifacts"])
        self.assertIn(f"{change}/specs/calc/spec.md", s["Artifacts"])
        self.assertIn("1.1 Add `add` to `src/calc.py`", s["Artifacts"])
        self.assertIn("tests-live-beside-code", s["Project test rules"])
        self.assertIn("docs/conventions.md", s["Project test rules"])
        task_1_1 = s["Surface rules per task"].split("1.2")[0]
        self.assertIn("small-functions", task_1_1)
        self.assertIn("gatedloop.test-quality", s["Built-in rules"])
        self.assertIn("loop-rules.md", s["Built-in rules"])
        self.assertIn("touch unit-ran", s["Runner"])
        self.assertFalse(ran, "the brief ran the unit gate")
        self.assertIn("tests/test_calc.py", s["Where tests live"])
        self.assertNotIn("docs/guide.md", s["Where tests live"])
        self.assertIn("tests/helpers.py", s["Shared fixtures and helpers"])

    def test_fixtures_found_by_name_when_no_rule_names_them(self):
        with tempfile.TemporaryDirectory() as tmp:
            root = _project(tmp, RICH_MANIFEST, {
                "docs/conventions.md": RULES_DOC.replace("`tests/helpers.py`", "the helpers"),
                "tests/test_calc.py": "",
                "tests/conftest.py": "",
            })
            s = _brief(root)
        self.assertIn("tests/conftest.py", s["Shared fixtures and helpers"])

    def test_each_none_line(self):
        manifest = 'gatesVersion: 1\ngates:\n  ci: "true"\nconventions:\n  rules-doc: docs/conventions.md\n'
        with tempfile.TemporaryDirectory() as tmp:
            root = _project(tmp, manifest, {
                "docs/conventions.md": "### small-functions\nApplies to: code\nRule: Keep functions small.\n",
            })
            s = _brief(root)
        self.assertIn("none", s["Project test rules"])
        self.assertIn("gates-init", s["Project test rules"])
        self.assertIn("none", s["Runner"])
        self.assertIn("none", s["Where tests live"])
        self.assertIn("none", s["Shared fixtures and helpers"])

    def test_unknown_change_fails_loud(self):
        with tempfile.TemporaryDirectory() as tmp:
            root = _project(tmp, RICH_MANIFEST, {"docs/conventions.md": RULES_DOC})
            result = subprocess.run(
                [sys.executable, str(GATES_SHIM), "tests", "brief", "no-such-change"],
                cwd=root, capture_output=True, text=True,
            )
        self.assertNotEqual(result.returncode, 0)
        self.assertIn("no-such-change", result.stderr)


if __name__ == "__main__":
    unittest.main()
