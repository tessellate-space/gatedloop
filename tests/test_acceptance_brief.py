"""Tests for `gates acceptance brief <change> [--out <path>]` (acceptance-gate
design D5): the deterministic, scenario-language view a human reads before
accepting an increment.

The brief is generated by the shim from data it owns -- the change's spec
scenarios, the files under the manifest's `acceptance.match` glob, and the
ledger rows recorded for the current head tree -- and never by a model.

Stdlib only, per `zero-dep-shim`. Run with:
    python3 -m unittest discover -s tests
"""

import importlib.machinery
import importlib.util
import json
import os
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
GATES_SHIM = REPO / "bin" / "gates"

_loader = importlib.machinery.SourceFileLoader("gates_shim_acc_brief", str(GATES_SHIM))
_spec = importlib.util.spec_from_loader(_loader.name, _loader)
gates = importlib.util.module_from_spec(_spec)
_loader.exec_module(gates)

BASE = """\
gatesVersion: 1
gates:
  ci: "true"
approval:
  plan: self
  acceptance: self
"""
MANIFEST_WITH_MATCH = BASE + 'acceptance:\n  match: "features/**/*.feature"\n'
MANIFEST_NO_MATCH = BASE

SPEC = """\
# Spec Delta

## ADDED Requirements

### Requirement: Login

#### Scenario: Login succeeds

- **WHEN** the right password is given
- **THEN** the user is in

#### Scenario: Password reset emails expire

- **WHEN** an hour passes
- **THEN** the link no longer works
"""

FEATURE = """\
Feature: auth

  Scenario:   login SUCCEEDS
    Given a user
"""

FOOTER = "does not mean the artifact asserts the scenario's outcome"


def _git(cwd, *args):
    return subprocess.run(
        ["git", *args], cwd=cwd, check=True, capture_output=True, text=True,
    ).stdout.strip()


def _run_gates(root, *args):
    return subprocess.run(
        [sys.executable, str(GATES_SHIM), *args],
        cwd=root, capture_output=True, text=True, env=dict(os.environ),
    )


def _make_repo(root: Path, manifest: str) -> None:
    _git(root, "init", "-b", "main")
    _git(root, "config", "user.email", "t@example.com")
    _git(root, "config", "user.name", "T")
    (root / ".gates.yaml").write_text(manifest)
    spec_dir = root / "openspec" / "changes" / "my-change" / "specs" / "auth"
    spec_dir.mkdir(parents=True)
    (spec_dir / "spec.md").write_text(SPEC)
    features = root / "features"
    features.mkdir()
    (features / "auth.feature").write_text(FEATURE)
    _git(root, "add", "-A")
    _git(root, "commit", "-m", "init")
    _git(root, "checkout", "-b", "my-change")
    (root / "impl.txt").write_text("the increment\n")
    _git(root, "add", "-A")
    _git(root, "commit", "-m", "task work")


def _append_rows(root: Path, rows: list[dict]) -> None:
    p = root / ".gatedloop" / "runs" / "my-change.jsonl"
    p.parent.mkdir(parents=True, exist_ok=True)
    with p.open("a") as f:
        for r in rows:
            f.write(json.dumps(r) + "\n")


def _brief(root: Path) -> str:
    r = _run_gates(root, "acceptance", "brief", "my-change")
    assert r.returncode == 0, r.stderr
    return r.stdout


def _scenario_line(text: str, title: str) -> str:
    lines = [ln for ln in text.splitlines() if title in ln and ("covered" in ln or "check by hand" in ln)]
    assert len(lines) == 1, f"expected one scenario line for {title!r}, got {lines}\n{text}"
    return lines[0]


def _check_by_hand_items(text: str) -> list[str]:
    lines = text.splitlines()
    start = next(i for i, ln in enumerate(lines) if ln.startswith("## Check these by hand"))
    items = []
    for ln in lines[start + 1:]:
        if ln.startswith("## "):
            break
        if ln.startswith("- "):
            items.append(ln)
    return items


class TestCoverage(unittest.TestCase):
    def test_one_covered_one_check_by_hand(self):
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp)
            _make_repo(root, MANIFEST_WITH_MATCH)
            text = _brief(root)

            self.assertIn("covered", _scenario_line(text, "Login succeeds"))
            self.assertNotIn("check by hand", _scenario_line(text, "Login succeeds"))
            self.assertIn("check by hand", _scenario_line(text, "Password reset emails expire"))

            items = _check_by_hand_items(text)
            self.assertEqual(len(items), 1, items)
            self.assertIn("Password reset emails expire", items[0])
            self.assertIn(FOOTER, text)

    def test_no_match_declared_everything_by_hand_with_reason(self):
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp)
            _make_repo(root, MANIFEST_NO_MATCH)
            text = _brief(root)

            self.assertIn("check by hand", _scenario_line(text, "Login succeeds"))
            self.assertIn("check by hand", _scenario_line(text, "Password reset emails expire"))
            self.assertEqual(len(_check_by_hand_items(text)), 2)
            self.assertIn("no acceptance artifact location is declared", text)


class TestDeterminismAndOutput(unittest.TestCase):
    def test_two_runs_are_byte_identical(self):
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp)
            _make_repo(root, MANIFEST_WITH_MATCH)
            self.assertEqual(_brief(root), _brief(root))

    def test_out_writes_the_same_bytes(self):
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp)
            _make_repo(root, MANIFEST_WITH_MATCH)
            expected = _brief(root)
            out = root / "brief.md"
            r = _run_gates(root, "acceptance", "brief", "my-change", "--out", str(out))
            self.assertEqual(r.returncode, 0, r.stderr)
            self.assertEqual(out.read_text(), expected)

    def test_committed_brief_does_not_disturb_the_normalized_tree(self):
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp)
            _make_repo(root, MANIFEST_WITH_MATCH)
            before = gates._normalize_tree(root, _git(root, "rev-parse", "HEAD^{tree}"))
            rel = ".gatedloop/runs/my-change.acceptance.md"
            r = _run_gates(root, "acceptance", "brief", "my-change", "--out", rel)
            self.assertEqual(r.returncode, 0, r.stderr)
            _git(root, "add", rel)
            _git(root, "commit", "-m", "commit the brief")
            after = gates._normalize_tree(root, _git(root, "rev-parse", "HEAD^{tree}"))
            self.assertEqual(before, after)


class TestTreeScopedVerdicts(unittest.TestCase):
    def test_head_tree_verdict_shown_older_tree_absent(self):
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp)
            _make_repo(root, MANIFEST_WITH_MATCH)
            head = _git(root, "rev-parse", "HEAD^{tree}")
            older = _git(root, "rev-parse", "main^{tree}")
            _append_rows(root, [
                {"ts": "2026-09-01T00:00:00+00:00", "gate": "live-check", "exit": 0,
                 "change": "my-change", "tree": older},
                {"ts": "2026-09-01T00:01:00+00:00", "gate": "verify", "exit": 0,
                 "change": "my-change", "tree": head},
            ])
            text = _brief(root)
            self.assertIn("verify: pass", text)
            self.assertIn("live-check: absent", text)
            self.assertIn("integration: absent", text)
            self.assertIn("review: absent", text)

    def test_ledger_rows_do_not_change_the_verdict_tree(self):
        """A verdict recorded before the ledger row was committed still
        speaks about the (ledger-normalized) head tree afterwards."""
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp)
            _make_repo(root, MANIFEST_WITH_MATCH)
            head = _git(root, "rev-parse", "HEAD^{tree}")
            _append_rows(root, [
                {"ts": "2026-09-01T00:01:00+00:00", "gate": "ci", "exit": 0,
                 "change": "my-change", "tree": head},
                {"ts": "2026-09-01T00:02:00+00:00", "gate": "review", "exit": 0,
                 "change": "my-change", "tree": head},
            ])
            _git(root, "add", ".gatedloop/runs/my-change.jsonl")
            _git(root, "commit", "-m", "ledger")
            text = _brief(root)
            self.assertIn("ci: pass", text)
            self.assertIn("review: clean", text)


class TestUnknownChange(unittest.TestCase):
    def test_missing_change_fails_loud(self):
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp)
            _make_repo(root, MANIFEST_WITH_MATCH)
            r = _run_gates(root, "acceptance", "brief", "no-such-change")
            self.assertNotEqual(r.returncode, 0)
            self.assertIn("no-such-change", r.stderr)


if __name__ == "__main__":
    unittest.main()
